# 只算真正的「空泛套话 + 抽象大词」。优美的叠词、比喻副词、形容词（缓缓、轻轻、温暖、冰冷、
# 仿佛、似乎、宛如、意味深长、怅然……）都是人类文学的常客，不算 AI 味，绝不能进黑名单，
