def _author_stats_fit(author, st):
    """文本节奏和这位作家的硬指标有多贴（越小越贴）"""
    m = author.get("metrics") or {}
    avg_lo, avg_hi = m.get("avg", (10, 28))
    d = 0.0
    if st["avg"] < avg_lo:
        d += (avg_lo - st["avg"]) * 0.6
    elif st["avg"] > avg_hi:
        d += (st["avg"] - avg_hi) * 0.6
    d += abs((m.get("dlg", 0.12) - st["dlg"])) * 12
    d += abs((m.get("cv", 0.42) - st["cv"])) * 8
    return d


def pick_author(text, profile=None, hint=""):
    """按题材 + 文本节奏挑一位作家当这次改写的基准。

    返回 (作者 dict, 选择理由)。挑不到就返回 (None, "")。
    """
    if not AUTHORS:
        return None, ""
    pname = (profile or {}).get("name", "通用")
    base = pname.split("·")[0]
    hint = str(hint or "")
    for name in AUTHORS:
        if name in hint:
            return AUTHORS[name], "你点名要学" + name + "的笔法"
    cands = [(n, a) for n, a in AUTHORS.items() if base in (a.get("tags") or [])]
    pref = _GENRE_PREF.get(base) or []
    if pref:
        cands = [(n, AUTHORS[n]) for n in pref if n in AUTHORS] or cands
    if not cands:
        cands = [(n, AUTHORS[n]) for n in _GENERAL_PICK if n in AUTHORS]
    if not cands:
        return None, ""
    st = _stats(text)
    order = {n: i for i, n in enumerate(pref)} if pref else {}
    ranked = sorted(cands, key=lambda x: (order.get(x[0], 99), _author_stats_fit(x[1], st)))
    top = ranked[:3]
    # 同样合适的几位之间轮换，避免每次都改成一个味儿
    seed = sum(ord(c) for c in str(text)[:60]) + len(str(text))
    pick = top[seed % len(top)]
    why = "按「%s」的节奏，选 %s 的笔法（%s）" % (pname, pick[0], pick[1].get("desc", ""))
    return pick[1], why


def blend(profile, author):
    """题材范式 + 作家笔法，合成这次改写真正用的基准"""
    if not author:
        return profile
    p = dict(profile or PROFILES["通用"])
    a = author
    am = dict(DEFAULT_METRICS)
    am.update(a.get("metrics") or {})
    principles = list(a.get("principles") or []) + [x for x in (p.get("principles") or [])[:3]]
    banned = list(dict.fromkeys(list(a.get("banned") or []) + list(p.get("banned") or [])))
    return {
        "name": "%s·%s" % (a.get("name", "?"), p.get("name", "")),
        "author": a.get("name", ""),
        "refs": [a.get("desc", "")] + list(p.get("refs") or [])[:2],
        "metrics": am,
        "principles": principles,
        "banned": banned,
        "samples": list(a.get("samples") or p.get("samples") or []),
        "desc": a.get("desc", ""),
    }


