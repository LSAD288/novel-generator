def match(genre="", style=""):
    """按题材/风格选范式，选不到用通用范式"""
    text = "".join([str(genre or ""), str(style or "")])
    for key, name in _KEYS:
        if key in text:
            return PROFILES[name]
    for key, name in _STYLE_HINT:
        if key in text:
            return PROFILES[name]
    return PROFILES["通用"]


def _stats(text):
    text = str(text or "")
    paras = [p for p in text.split("\n") if p.strip()]
    sents = [s.strip() for s in re.findall(r"[^。！？!?…\n]+[。！？!?…]?", text) if s.strip()]
    lens = [len(s) for s in sents] or [0]
    avg = sum(lens) / len(lens)
    var = sum((x - avg) ** 2 for x in lens) / len(lens)
    cv = (var ** 0.5 / avg) if avg else 0.0
    chars = max(1, len(re.sub(r"\s+", "", text)))
    dlg = sum(1 for s in sents if ("「" in s or "“" in s or "\"" in s))
    four = len(FOUR_CHAR.findall(text))
    abstract = len(ABSTRACT_WORDS.findall(text))
    ai = len(AI_SENT.findall(text))
    para_avg = chars / max(1, len(paras))
    plens = [len(re.sub(r"\s+", "", p)) for p in paras] or [0]
    pmean = sum(plens) / len(plens)
    pvar = sum((x - pmean) ** 2 for x in plens) / len(plens)
    ends = set()
    for s in sents:
        m = re.search(r"[。！？!?…]+$", s)
        if m:
            ends.add(m.group(0)[0])
    return {
        "chars": chars, "sents": len(sents), "avg": round(avg, 1), "cv": round(cv, 2),
        "dlg": round(dlg / max(1, len(sents)), 2), "paras": len(paras),
        "para_avg": round(para_avg, 1),
        "para_cv": round((pvar ** 0.5 / pmean) if pmean else 0.0, 2),
        "end_kinds": len(ends),
        "four_per100": round(four * 100.0 / chars, 2),
        "abstract_per100": round(abstract * 100.0 / chars, 2),
        "ai_hits": ai,
    }


def score(text, profile=None):
    """按范式给文笔打分 0~100，并返回扣分理由（可直接显示给用户）"""
    p = profile or PROFILES["通用"]
    m = dict(DEFAULT_METRICS)
    m.update(p.get("metrics") or {})
    st = _stats(text)
    s = 100.0
    why = []
    lo, hi = m["avg"]
    if st["avg"] < lo:
        s -= min(18, (lo - st["avg"]) * 1.6)
        why.append("句子偏短碎")
    elif st["avg"] > hi:
        s -= min(22, (st["avg"] - hi) * 1.4)
        why.append("句子偏长")
    if st["cv"] < m["cv"]:
        s -= min(20, (m["cv"] - st["cv"]) * 46)
        why.append("句长太均匀")
    if st["dlg"] < m["dlg"]:
        s -= min(10, (m["dlg"] - st["dlg"]) * 55)
        why.append("没有对话")
    if st["four_per100"] > m["four"]:
        s -= min(14, (st["four_per100"] - m["four"]) * 4.2)
        why.append("四字格堆叠")
    if st["abstract_per100"] > m["abstract"]:
        s -= min(30, (st["abstract_per100"] - m["abstract"]) * 9.5)
        why.append("抽象词太多")
    if st["ai_hits"]:
        s -= min(26, st["ai_hits"] * 6.5)
        why.append("AI 句式")
    plo, phi = m["para"]
    if st["paras"] >= 3 and st["para_avg"] > phi:
        s -= min(10, (st["para_avg"] - phi) * 0.06)
        why.append("段落太长")
    # 太整齐：句尾标点千篇一律、段落长度像切好的豆腐块
    if st["sents"] >= 6 and st["end_kinds"] <= 1:
        s -= 6
        why.append("句尾太齐")
    if st["paras"] >= 4 and st["para_cv"] < 0.18:
        s -= 5
        why.append("段落太齐")
    score_i = int(max(0, min(100, round(s))))
    return {"score": score_i, "why": why, "stats": st, "profile": p["name"]}


def rules(profile, strict=False):
    """给改写模型的范式规则（正向示范 + 硬指标 + 禁词）"""
    p = profile or PROFILES["通用"]
    m = dict(DEFAULT_METRICS)
    m.update(p.get("metrics") or {})
    lines = ["【本次不以原文文笔为基准，按下面的题材笔法重写】",
             "【先记住：优美不是 AI 味，空洞才是。好词好句、贴切的比喻、有质感的形容词、四字格、"
             "抒情，只要是贴着具体的人事物写的，就放心用，还要主动写；只删空洞套话和机械重复，"
             "绝不为「像人」就把文笔挖空、削成大白话。】",
             "【反例·绝不这样改】原文「檐角的雨水一颗一颗坠下来，打在青石板上，溅起一线细白的水花」"
             "改成「雨水落下来。石板上有水花。」——这叫挖骨削肉，是毁稿。"
             "正解是保留骨肉：「檐角的雨水一颗接一颗砸在青石板上，碎成细白的一线。」",
             "【硬指标】改写后字数不得少于原文的 85%；形容词、比喻、叠词、四字格的密度不得少于原文的"
             "一半；改完读一遍，若比原文更干、更像小学生作文，就重写。"]
    if p.get("author"):
        lines.append("基准作家：%s（写得像他，不是写得像原文）" % p["author"])
        lines.append("这位作家的笔法：%s" % (p.get("desc") or ""))
        lines.append("范式：%s" % p["name"])
    else:
        lines.append("范式：%s（参考：%s）" % (p["name"], "、".join(p.get("refs") or [])))
    lines.append("硬指标：平均句长 %d-%d 字；句长要长短交错；四字格每百字不超过 %.1f 个；"
                 "抽象评价词每百字不超过 %.1f 个；段落 %d-%d 字；有对话的地方用短对白。"
                 % (m["avg"][0], m["avg"][1], m["four"], m["abstract"], m["para"][0], m["para"][1]))
    lines.append("写法：")
    lines += ["- " + x for x in (p.get("principles") or [])]
    lines.append("节奏：句尾不要一律用句号，问句、叹句、省略号、破折号都可以有；段落有长有短，不要齐整。")
    if p.get("banned"):
        lines.append("禁词：" + "、".join(p["banned"]))
    if p.get("samples"):
        lines.append("示范（只学笔法，不要照抄内容）：")
        lines += ["- " + x for x in p["samples"]]
    if strict:
        lines.append("这一段原文本身就写得很空，允许换掉大部分句子，但必须留下原文里具体的人、事、物。")
    return "\n".join(lines)
