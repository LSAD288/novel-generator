def apply_ultimate_humanizer(text, intensity=8):
    """应用终极AI痕迹消除
    
    Args:
        text: 需要处理的文本
        intensity: 处理强度（1-10）
    
    Returns:
        处理后的文本
    """
    if HAS_ULTIMATE_AI_HUMANIZER and 'ultimate_humanizer' in globals():
        try:
            return ultimate_humanizer.humanize(text, intensity=intensity)
        except Exception as e:
            print(f"终极AI痕迹消除失败: {e}")
    
    # 如果没有终极AI痕迹消除系统，使用内置的简单处理
    return _simple_humanize(text, intensity)


def _simple_humanize(text, intensity=8):
    """简单的AI痕迹消除处理"""
    
    # AI高频词汇替换表
    replacements = {
        "仿佛": "像",
        "似乎": "好像",
        "宛如": "像",
        "犹如": "像",
        "恍若": "像",
        "不禁": "",
        "不由得": "",
        "不由自主": "",
        "情不自禁": "",
        "油然而生": "",
        "扑面而来": "迎面而来",
        "映入眼帘": "看见",
        "映入眼帘的是": "眼前是",
        "映照着": "照着",
        "交织着": "混合着",
        "弥漫着": "充满",
        "笼罩着": "覆盖着",
        "渗透着": "渗透",
        "透露出": "露出",
        "流露出": "露出",
        "散发着": "发出",
        "洋溢着": "充满",
        "充满着": "满是",
        "蕴含着": "包含",
        "承载着": "承载",
        "诠释着": "诠释",
        "彰显着": "彰显",
        "体现着": "体现",
        "展现着": "展现",
        "呈现出": "呈现",
        "勾勒出": "勾勒",
        "描绘出": "描绘",
        "刻画出": "刻画",
        "渲染出": "渲染",
        "营造出": "营造",
        "构筑起": "构筑",
        "搭建起": "搭建",
    }
    
    # 根据强度决定替换比例
    if intensity >= 8:
        # 高强度：全部替换
        for old, new in replacements.items():
            text = text.replace(old, new)
    elif intensity >= 5:
        # 中等强度：替换部分
        for old, new in list(replacements.items())[:len(replacements)//2]:
            text = text.replace(old, new)
    else:
        # 低强度：只替换最明显的
        for old in ["仿佛", "似乎", "不禁", "不由得"]:
            if old in replacements:
                text = text.replace(old, replacements[old])
    
    return text


