@dataclass
class CharacterIdentity:
    """角色身份信息"""
    name: str
    identity_type: str = ""
    social_status: str = ""
    knowledge_level: str = ""
    information_channels: List[str] = field(default_factory=list)
    behavioral_constraints: List[str] = field(default_factory=list)
    typical_behaviors: List[str] = field(default_factory=list)
    forbidden_behaviors: List[str] = field(default_factory=list)
    relationships: Dict[str, str] = field(default_factory=dict)


@dataclass
class InformationSource:
    """信息来源记录"""
    info_id: str
    content: str
    source_type: str
    source_character: str
    acquisition_time: str
    acquisition_location: str
    witnesses: List[str] = field(default_factory=list)
    reliability: float = 1.0


@dataclass
class ToolmanIssue:
    """工具人问题记录"""
    issue_type: ToolmanPattern
    character_name: str
    description: str
    location: str
    severity: str
    suggestion: str
    original_text: str
    fixed_text: str = ""


