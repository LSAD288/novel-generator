def detect_toolman_issues(text: str, characters: Dict = None) -> List[Dict]:
    """检测文本中的工具人问题"""
    detector = get_toolman_detector()
    
    char_identities = {}
    if characters:
        for name, info in characters.items():
            if isinstance(info, dict):
                char_identities[name] = CharacterIdentity(
                    name=name,
                    identity_type=info.get("identity_type", ""),
                    social_status=info.get("social_status", ""),
                    knowledge_level=info.get("knowledge_level", ""),
                    information_channels=info.get("information_channels", []),
                    behavioral_constraints=info.get("behavioral_constraints", []),
                    typical_behaviors=info.get("typical_behaviors", []),
                    forbidden_behaviors=info.get("forbidden_behaviors", []),
                    relationships=info.get("relationships", {})
                )
    
    issues = detector.detect_toolman_patterns(text, char_identities)
    
    return [
        {
            "type": issue.issue_type.value,
            "character": issue.character_name,
            "description": issue.description,
            "location": issue.location,
            "severity": issue.severity,
            "suggestion": issue.suggestion,
            "original_text": issue.original_text
        }
        for issue in issues
    ]


